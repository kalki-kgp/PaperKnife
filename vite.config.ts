const escapeHtml = (value: string) =>
  value.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;')

const routeJsonLd = (routePath: string, url: string) => {
  const name = shortName(routePath)
  const graph: Record<string, unknown>[] = [
    {
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'PaperKnife', item: `${SITE_URL}/` },
        { '@type': 'ListItem', position: 2, name, item: url }
      ]
    }
  ]
  if (isToolPath(routePath)) {
    graph.push({
      '@type': 'SoftwareApplication',
      name,
      url,
      applicationCategory: 'UtilitiesApplication',
      operatingSystem: 'Web Browser',
      description: routeSeo[routePath].description,
      offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' }
    })
  }
  const json = JSON.stringify({ '@context': 'https://schema.org', '@graph': graph }, null, 2)
  return `    <script type="application/ld+json">\n${json}\n    </script>\n  `
}

const buildRedirects = () =>
  `# Generated by the paperknife-seo-html plugin in vite.config.ts. Do not edit.
#
# Routes are NOT listed here. Each one has its own <route>.html file and
# Workers' html_handling resolves /merge to merge.html by itself. Rewriting
# /merge -> /merge.html explicitly loops: the rewrite lands on merge.html and
# extension-stripping bounces it straight back to /merge.
#
# Anything without a matching file falls through to not_found_handling
# ("404-page" in wrangler.jsonc), so scanner probes for /wp-admin, /.env and
# ~240 PHP shell paths get the ad-free 404 rather than a 200. See e03579b.

# No HTML file of their own; the service worker handles these.
/share-target                   /   200
/__paperknife_pending_share__   /   200
`

const buildSitemap = (paths: string[]) => {
  const entries = paths
    .filter((routePath) => !routeSeo[routePath].noindex)
    .map((routePath) => {
      const loc = routePath === '/' ? `${SITE_URL}/` : `${SITE_URL}${routePath}`
      return [
        '  <url>',
        `    <loc>${loc}</loc>`,
        `    <changefreq>${sitemapChangefreq(routePath)}</changefreq>`,
        `    <priority>${sitemapPriority(routePath)}</priority>`,
        '  </url>'
      ].join('\n')
    })
    .join('\n')
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`
}

/**
 * Emits a real HTML file per route, plus a sitemap derived from the same
 * source. The SPA previously served one index.html for every path, so every
 * tool page carried the homepage's title and a canonical pointing at "/" —
 * telling Google that all 22 sitemap URLs were duplicates of the homepage.
 */
function perRouteSeoHtml(): Plugin {
  return {
    name: 'paperknife-seo-html',
    apply: 'build',
    closeBundle() {
      const outDir = path.resolve(rootDir, 'dist')
      const indexPath = path.join(outDir, 'index.html')
      if (!fs.existsSync(indexPath)) return
      const shell = fs.readFileSync(indexPath, 'utf-8')

      const paths = Object.keys(routeSeo).filter(
        (routePath) =>
          !(routePath === '/pdf-to-text' && process.env.VITE_DISABLE_OCR === 'true')
      )

      for (const routePath of paths) {
        const seo = routeSeo[routePath]
        const url = routePath === '/' ? `${SITE_URL}/` : `${SITE_URL}${routePath}`
        const title = escapeHtml(seo.title)
        const description = escapeHtml(seo.description)

        let html = shell
          .replace(/<title>[\s\S]*?<\/title>/, `<title>${title}</title>`)
          .replace(/<meta\s[^>]*name="description"[^>]*>/, `<meta name="description" content="${description}" />`)
          .replace(/<link rel="canonical"[^>]*>/, `<link rel="canonical" href="${url}" />`)
          .replace(/<meta\s[^>]*property="og:title"[^>]*>/, `<meta property="og:title" content="${title}" />`)
          .replace(/<meta\s[^>]*property="og:description"[^>]*>/, `<meta property="og:description" content="${description}" />`)
          .replace(/<meta\s[^>]*property="og:url"[^>]*>/, `<meta property="og:url" content="${url}" />`)
          .replace(/<meta\s[^>]*name="twitter:title"[^>]*>/, `<meta name="twitter:title" content="${title}" />`)
          .replace(/<meta\s[^>]*name="twitter:description"[^>]*>/, `<meta name="twitter:description" content="${description}" />`)

        if (seo.noindex) {
          html = html.replace(/<meta\s[^>]*name="robots"[^>]*>/, '<meta name="robots" content="noindex, follow" />')
        }

        if (routePath !== '/') {
          // The FAQ answers homepage questions; repeating it on every tool
          // page is duplicate structured data.
          html = html.replace(/\s*<script type="application\/ld\+json">[\s\S]*?"FAQPage"[\s\S]*?<\/script>/, '')
          html = html.replace('</head>', `${routeJsonLd(routePath, url)}</head>`)
        }

        const file = routePath === '/' ? 'index.html' : `${routePath.slice(1)}.html`
        fs.writeFileSync(path.join(outDir, file), html)
      }

      fs.writeFileSync(path.join(outDir, 'sitemap.xml'), buildSitemap(paths))
      fs.writeFileSync(path.join(outDir, '_redirects'), buildRedirects())
      this.warn(`emitted ${paths.length} per-route HTML files + sitemap.xml`)
    }
  }
}

